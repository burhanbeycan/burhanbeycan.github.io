import numpy as np

from .crop import load_cohort
from .design import POOL, design, folds, series_id, synthetic_surface

MODE = "petox_design"


def register(app, number):
    app["fields"][0]["options"].append({"value":MODE,"label":"PEtOx · select the next concentration and feed"})
    for key,label,content,help_text in [
        ("design_observed","Measured cohort (CSV)",load_cohort("flow_feed"),"One reactor, compatible SEC method and terminal chemistry. Use distinct IDs for independent preparations."),
        ("design_pool","Candidate concentration and feed (CSV)",POOL,"M0_M in mol/L and feed = [EtOx]₀/[MeOTs]₀. Supply feasible unmeasured candidates for your protocol.")]:
        app["fields"].append({"key":key,"label":label,"default":content,"type":"textarea","unit":"","group":"Design data",
                              "show_if":{"key":"model","value":MODE},"help":help_text})
    app["fields"].extend([
        number("design_T","Temperature of selected cohort",160,"°C",0,200,"Protocol","Match an observed condition.",MODE),
        number("design_t","Reaction time of selected cohort",5,"min",1e-6,1e5,"Protocol","Match observed hold or residence time.",MODE)])
    app["presets"].append({"name":"PEtOx · next feed/concentration against four measured flow feeds",
        "description":"Prospective log-determinant design. Existing measurements are from Baeten et al., Table S1. Candidate grid is hypothetical.",
        "inputs":{"model":MODE,"design_observed":load_cohort("flow_feed"),"design_pool":POOL,"design_T":160,"design_t":5}})
    app["presets"].append({"name":"PEtOx · synthetic residual recovery",
        "description":"Software control with a known log-linear response in two mock studies. Quantitative recovery tests the algorithm.",
        "inputs":{"model":MODE,"design_observed":synthetic_surface(),"design_pool":"M0_M,feed\n1.5,30\n3,60\n5,90",
                  "design_T":100,"design_t":10}})
    app["models"].append({"name":"Feed/concentration learning at fixed T and hold time",
        "equation":"log(Mn,SEC / Mn,kin) = β₀ + βc log₂([M]₀ / 3 M) + βf log₂(feed / 60); gain = ½ ln(1 + φᵀA⁻¹φ)",
        "assumptions":["Fixed assay, reactor, reaction temperature, time and nominal chain ends; feasible unmeasured candidate pool",
                       "A = I + Σ w φφᵀ; w gives each represented reaction series unit total weight. This is a regularized information-design criterion."],
        "references":["crop_flow","crop_rates","design_info"]})
    app["references"].append({"id":"design_info","title":"Optimal experimental design: formulations and computations.",
                              "url":"https://doi.org/10.1017/S0962492924000023"})


def render(p, metric):
    rows, ranked, model, reason = design(p["design_observed"], p["design_pool"], p["design_T"], p["design_t"])
    next_recipe = ranked[0][0] if ranked else None
    warnings = []
    if all(r.paper.startswith("synthetic-control-") for r in rows):
        warnings.append("Synthetic software control. The coefficients and assessed masses were generated by a known equation. Holdout errors here measure numerical recovery.")
    if model is None:
        warnings.append(reason+" Residual-adjusted candidate Mn is unavailable.")
    if not 60 <= p["design_T"] <= 140:
        warnings.append("Temperature falls outside the 60–140 °C measured range in the kinetic coefficient source. Theoretical Mn is an extrapolation.")
    tables = []
    if ranked:
        tables.append({"title":"Prospective unmeasured designs in descending information gain", "columns":
            ["Rank","[M]₀ (mol/L)","Feed (mol/mol)","[I]₀ (mol/L)","Gain (nat)","Kinetic Mn (g/mol)","Local residual-adjusted SEC Mn (g/mol)"],
            "rows":[[i,r.M,r.feed,r.I,g,r.predict()[1],pred] for i,(r,g,pred) in enumerate(ranked,1)]})
    else:
        warnings.append("Every candidate in this pool was already measured at the selected condition.")
    if model:
        tables.append({"title":"Empirical changes in the SEC / kinetic Mn ratio","columns":["Coefficient","Value (log ratio)"],
            "rows":[[label,float(value)] for label,value in zip(("Intercept at 3 M / feed 60","For doubled concentration at fixed feed","For doubled feed at fixed concentration"),model.coefficients)]})
    scores = []
    diagnostics = []
    for split,name in [("paper","Entire publication"),("joint","Both unseen concentration and feed; independent series")]:
        fixed, paired, residual = [], [], []
        for group,count,tested,why in folds(rows,split):
            learned = 0
            for row, baseline, estimate in tested:
                error=100*abs(baseline-row.Mn)/row.Mn
                fixed.append(error)
                if estimate is not None:
                    learned += 1
                    paired.append(error)
                    residual.append(100*abs(estimate-row.Mn)/row.Mn)
            diagnostics.append([name,str(group),count,len(tested),learned,why])
        for label,errs in [("Kinetic baseline (all)",fixed),("Kinetic baseline (paired)",paired),("Residual (paired)",residual)]:
            scores.append([name,label,len(errs),float(np.median(errs)) if errs else None,float(np.percentile(errs,90)) if errs else None])
    tables.extend([
        {"title":"Blind validation coverage and absolute relative errors","columns":["Grouping","Model","Scored records","Median (%)","P90 (%)"],"rows":scores},
        {"title":"Fit eligibility in each fold","columns":["Grouping","Holdout","Training rows","Test rows","Residual scores","Training status"],"rows":diagnostics}])
    tables.append({"title":"What to record for the selected experiment",
                   "columns":["Observation","Purpose"],
                   "rows":[["SEC Mn with solvent, calibration and detector","Update the recipe-only residual using the same assay."],
                           ["Independent conversion (e.g. quantitative NMR)","Diagnose a propagation discrepancy; retain as an observation."],
                           ["Full SEC trace with retention axis and calibration","Inspect shoulders or high-mass tails if transfer or branching is suspected."],
                           ["Independent preparation ID, temperature profile and residence/hold time","Prevent repeated injections or time points from becoming independent validation folds."]]})
    return {"metrics":[metric("next_M","Next candidate [M]₀",next_recipe.M if next_recipe else None,"mol/L"),
            metric("next_feed","Next candidate feed",next_recipe.feed if next_recipe else None,"mol/mol"),
            metric("measured","Matched measured records",len(rows),"records"),metric("groups","Reaction series",len({series_id(r) for r in rows}),"series")],
            "tables":tables,"plots":[],"handoffs":[],"warnings":warnings,
            "notes":["Nominal EtOx/MeOTs/MeCN chemistry. The search ranks only entered feasible conditions. The pool is a proposed design; absolute Mn uses the published fixed kinetic baseline.",
                     "Gain is a model-dependent design score in natural-log units. The design assumes equal standardized future measurement precision. It is not a calibrated predictive interval or an estimate of experimental success.",
                     "Re-enter the measured SEC result and its provenance, then rerun to update the design. Repeated time points are not independent preparations; each series has unit fitting weight.",
                     "The optional three-coefficient residual is fitted only when the training design supports concentration and feed changes. A future adjusted Mn is displayed within the convex hull of measured designs; blind holdouts deliberately also test extrapolation.",
                     "Recorded conversion never enters acquisition, fitting or prediction. Keep cohorts comparable in reactor, assay, preparation and nominal end groups. Additional independent publications and concentration levels are needed to establish transfer."]}
