'use strict';
const fs=require('node:fs'),path=require('node:path');
const {readCore}=require('./build-hydro-family.cjs');
const {evaluateStack}=require('./hydro-stack.cjs');
const {evaluateReferences,evaluateNewStudy}=require('./hydro-reference.cjs');
function build(root) {
  const core=readCore(path.join(root,'family-inputs','hydro-family-data.csv'));
  const old=require(path.join(root,'hydro-family-benchmark.js'));
  const folds=old.folds.map(fold=>evaluateStack(core.filter(r=>fold.train_ids.includes(r.id)),fold.rows,fold.group,fold.split,fold.label));
  const chemistry=folds.filter(f=>f.split==='chemistry');
  const balanced={};
  for(const name of ['mass','size','stack']){
    const avg=field=>chemistry.reduce((a,f)=>a+f.methods[name][field],0)/chemistry.length;
    balanced[name]={mape:avg('mape'),mae_log:avg('mae_log')};
  }
  const colby=readCore(path.join(root,'family-inputs','hydro-colby1987.csv'));
  return {version:1,units:'mL/g',catalogue:core,balanced,folds,references:evaluateReferences(core),externalStudy:evaluateNewStudy(core,colby)};
}
if(require.main===module) {
  const root=path.resolve(process.argv[2]||'dist'),dest=process.argv[3]||path.join(root,'hydro-stack-results.js');
  const data=build(root);
  fs.writeFileSync(dest,'/* Generated by build-hydro-stack.cjs */\n(function(root){const result='+JSON.stringify(data,null,2)+';\nroot.HYDRO_STACK=result;if(typeof module!=="undefined"&&module.exports)module.exports=result;})(typeof window==="undefined"?globalThis:window);\n');
}
module.exports={build};
