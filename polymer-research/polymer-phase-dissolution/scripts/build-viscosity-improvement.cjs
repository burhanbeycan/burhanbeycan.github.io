'use strict';
const fs = require('node:fs');
const path = require('node:path');
const {present} = require('./hydro-protocols.cjs');
const base = path.resolve(process.argv[2] || 'dist');
const read = name => JSON.parse(fs.readFileSync(path.join(base, 'family-inputs', name), 'utf8'));
const load = name => require(path.join(base, name));
const theta = read('protocols.json');
const hydro = present(load('hydro-stack-results.js'));
const pvoh = read('pvoh-transfer-protocols.json');
const shape = read('hpam-shape.json');
const physics = theta.find(p => p.id === 'theta-one-reference');
const adaptive = {...physics, id:'theta-reference-weights',label:'θ · referansın öğrenilmiş ağırlığı',
  description:'Aynı literatür referansı verildiğinde öğrenilmiş düzeltmenin basit θ ölçeklemesine katkısı.',
  baseline:'Referansla θ ölçeklemesi',candidate:'Öğrenilmiş referans ağırlığı',
  method:'Her iki tahmin aynı ölçüm ve aynı kütle üssünü kullanır. Ağırlıklı model, referansın logaritmik sapmasının ne kadarını tutacağını hedef aile dışında kalan kimyalardan öğrenir.',
  limit:'Hedef numune hesapta kullanılmaz. Eski modelle karşılaştırılan 51 saklı numune burada da aynıdır. Aynı kimyadan referans bulunması bu sınamanın önkoşuludur.',
  rows:physics.rows.map(r=>({...r,baseline:r.physical,candidate:r.adaptive}))};
const hpam={id:'hpam-shape',label:'HPAM · akış eğrisinde fiziksel kısıtlar',metric:'RMSE',unit:'mPa·s',aggregation:'pooled',
  baseline:'İkinci derece model',candidate:'Eğimleri kısıtlanmış model',
  scope:'9 formülasyon · 15 farklı koşul · 20 ölçüm · 24 °C',
  description:'Tuz, kayma ve polimer derişiminin yerel etki yönlerini kısıtlamanın görünür viskozite hatasına etkisi.',
  method:'Her turda bir polimer–tuz bileşimi tüm kayma hızlarıyla birlikte dışarıda bırakılır. Aynı koşuldaki tekrarlar önce ortalanır. İki modelin log girdileri ve ikinci derece terimleri aynıdır. Adayda eğitim noktalarının log-uzaydaki dışbükey zarfı içinde polimer eğimi pozitif veya sıfır, tuz ve kayma eğimleri negatif veya sıfır olmaya zorlanır.',
  limit:'Kısıtlar bu çözelti ve tasarım aralığı için incelendi. Önceki en düşük hatalı ikinci derece yüzey daha düşük RMSE verdi. Sahadaki başka bir HPAM derecesine aktarım ölçülmedi.',
  links:[{label:'Akbari ve ark. · deney tablosu',url:'https://doi.org/10.1007/s13202-017-0375-6'},{label:'HPAM akış eğrisi',url:'viscosity-formulation.html'}], rows:shape.rows};
const external = read('external-theta-protocols.json');
const records = [physics,adaptive,...hydro.slice(0,2),...pvoh,...theta.filter(p => p!==physics),...external,...hydro.slice(2),hpam];
const ids=new Set();
for(const p of records){
  if(!p.id || ids.has(p.id) || !p.rows.length) throw Error('Empty or duplicate comparison: '+p.id);
  ids.add(p.id);
  if(new Set(p.rows.map(r=>r.id)).size!==p.rows.length) throw Error('Repeated sample: '+p.id);
  for(const row of p.rows) if(!row.id || !row.group || ![row.baseline,row.candidate,row.observed].every(v=>Number.isFinite(v)&&v>0)) throw Error('Invalid pair: '+row.id);
}
const payload={protocols:records};
const json=JSON.stringify(payload,null,2);
fs.writeFileSync(path.join(base,'viscosity-improvement-data.js'),'/* Generated by build-viscosity-improvement.cjs */\n(function(root){const data='+json+';root.ViscosityImprovement=data;if(typeof module!=="undefined"&&module.exports)module.exports=data;})(typeof window==="undefined"?globalThis:window);\n');
console.log(records.map(p=>p.id+' ('+p.rows.length+')').join(', '));
