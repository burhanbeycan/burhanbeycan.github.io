"""Write the four pure-liquid reference states used by the viscosity workspace.

Install CoolProp==8.1.0, then run this file. An optional output path can be
given when recreating the published asset in a different directory.
"""

import json
import sys
from pathlib import Path

import CoolProp
from CoolProp.CoolProp import PhaseSI, PropsSI


PRESSURE_PA = 101_325
EXPECTED_VERSION = "8.1.0"
REFERENCES = {
    "Benzene": ("Avgeri vd. (2014)", "10.1063/1.4892935"),
    "Toluene": ("Avgeri vd. (2015)", "10.1063/1.4926955"),
    "CycloHexane": ("Tariq vd. (2014)", "10.1063/1.4891103"),
}
STATES = [
    ("Benzene", 298.15),
    ("Toluene", 298.15),
    ("Toluene", 303.15),
    ("CycloHexane", 307.65),
]


def liquid_reference(fluid, temperature):
    fluid_key = "HEOS::" + fluid
    state = ("T", temperature, "P", PRESSURE_PA, fluid_key)
    if PhaseSI(*state) != "liquid":
        raise ValueError(f"Expected liquid for {fluid} at {temperature} K")
    viscosity_pa_s = PropsSI("VISCOSITY", *state)
    label, doi = REFERENCES[fluid]
    return {
        "id": f"{fluid.lower()}-{temperature:.2f}K-101325Pa",
        "solvent": fluid.lower(),
        "T_K": temperature,
        "p_Pa": PRESSURE_PA,
        "eta_mPa_s": round(1000 * viscosity_pa_s, 9),
        "method": "CoolProp 8.1.0 · HEOS · saf sıvı referans korelasyonu",
        "source": {
            "label": label,
            "url": f"https://doi.org/{doi}",
            "doi": doi,
            "implementation": f"https://coolprop.org/fluid_properties/fluids/{fluid}.html",
        },
    }


def main():
    if CoolProp.__version__ != EXPECTED_VERSION:
        raise RuntimeError(f"Reproduction requires CoolProp {EXPECTED_VERSION}.")
    data = {
        "engine": f"CoolProp {CoolProp.__version__}",
        "revision": CoolProp.__gitrevision__,
        "records": [liquid_reference(*state) for state in STATES],
    }
    payload = json.dumps(data, ensure_ascii=False, indent=2)
    js = (
        "// Generated by generate-solvent-viscosities.py from CoolProp transport correlations.\n"
        "(function (root) {\n"
        f"  const data = {payload};\n"
        "  root.VIS_SOLVENT = data;\n"
        '  if (typeof module !== "undefined" && module.exports) module.exports = data;\n'
        '})(typeof window !== "undefined" ? window : globalThis);\n'
    )
    dest = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).with_name("viscosity-solvent-data.js")
    dest.write_text(js, encoding="utf-8")


if __name__ == "__main__":
    main()
