// node scripts/build-hydro-family.cjs WEB_ROOT [OUTPUT]
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {report}=require('./hydro-family-engine.cjs');
function loadBrowser(file,key) {
  const context={window:{}};
  vm.runInNewContext(fs.readFileSync(file,'utf8'),context,{filename:file});
  return structuredClone(context.window[key]);
}
function readCore(file) {
  const [header,...raw]=fs.readFileSync(file,'utf8').trim().split(/\r?\n/);
  const keys=header.split(',');
  const numeric=new Set(['M_g_mol','Rg_nm','eta_mL_g','T_K','table','original_ref']);
  return raw.map(line=>Object.fromEntries(line.split(',').map((v,i)=>[keys[i],numeric.has(keys[i])?Number(v):v])));
}
function scoreFiles(coreFile,psFile,pullulanFile) {
  const core=readCore(coreFile);
  const ps=loadBrowser(psFile,'VIS_INTRINSIC').rows.filter(r=>r.study==='einaga1979' && r.matched_Rg && r.solvent==='benzene')
   .map(r=>({id:r.id,family:'ps',backbone:'styrenic',solvent:'benzene',T_K:r.T_K,mass_basis:'Mw',M_g_mol:r.Mw_g_mol,
     Rg_nm:r.Rg_nm,eta_mL_g:r.eta_mL_g,source_doi:r.source_doi,radius_doi:r.Rg_source_doi,table:1}));
  const pullulanData=loadBrowser(pullulanFile,'FAMILY_EXTRA');
  const pullulan=pullulanData.rows.filter(r=>r.study==='kato1984'&&r.use_primary).map(r=>({id:r.id,family:'pullulan',
    backbone:'polysaccharide',solvent:r.solvent,T_K:r.T_K,mass_basis:'Mw',M_g_mol:r.Mw_g_mol,Rg_nm:r.Rg_nm,
    eta_mL_g:r.eta_mL_g,source_doi:'10.1021/ma00139a016',table:1}));
  if(!ps.length || !pullulan.length)throw Error('Bağımsız sınama örnekleri eksik.');
  return report(core,{'ps-benzene':ps,'pullulan-water':pullulan});
}
if(require.main===module) {
  const root=path.resolve(process.argv[2]||'.');
  const data=scoreFiles(path.join(root,'family-inputs','hydro-family-data.csv'),path.join(root,'viscosity-intrinsic-data.js'),path.join(root,'extra-families-data.js'));
  const out=process.argv[3]||path.join(root,'hydro-family-benchmark.js');
  const json=JSON.stringify(data,null,2);
  fs.writeFileSync(out,'/* Generated by build-hydro-family.cjs */\n(function(root){const result='+json+';\nroot.HYDRO_BENCHMARK=result;if(typeof module!=="undefined"&&module.exports)module.exports=result;})(typeof window==="undefined"?globalThis:window);\n');
}
module.exports={scoreFiles,readCore};
