'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const web=process.argv[2]?path.resolve(process.argv[2]):fs.existsSync(path.join(root,'dist','family-engine.js'))?path.join(root,'dist'):root;
const destination=process.argv[3]?path.resolve(process.argv[3]):path.join(web,'family-inputs');
const model=require(path.join(web,'family-engine.js'));
const context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(web,'family-intrinsic-data.js'),'utf8'),context);
const rows=context.window.THETA_FAMILY_DATA.rows;
const doc=model.buildBenchmark(rows);
fs.mkdirSync(destination,{recursive:true});
const json=JSON.stringify(doc,null,2);
fs.writeFileSync(path.join(web,'theta-family-benchmark.js'),'// Generated by validate-theta-families.cjs\nwindow.THETA_FAMILY_BENCHMARK='+json+';\n');
fs.writeFileSync(path.join(destination,'theta-family-benchmark.json'),json+'\n');
const keys=['id','family','chemistry','mass','mass_basis','observed','theta','ridge','domain','descriptorDomain','ref','source_ref','source_doi','solvent','T_C','temperature_basis'];
const header=['id','held_family','chemistry','mass_g_mol','mass_basis','observed_eta_mL_g','theta_baseline_eta_mL_g','ridge_eta_mL_g','mass_domain','descriptor_domain','table_reference','reference_id','source_doi','solvent','T_C','temperature_basis','training_ids'];
const escape=x=>'"'+String(x??'').replaceAll('"','""')+'"';
const table=[header,...doc.families.flatMap(f=>f.folds.map(r=>[...keys.map(k=>r[k]),f.trainingIds.join('|')]))];
fs.writeFileSync(path.join(destination,'theta-held-families.csv'),table.map(line=>line.map(escape).join(',')).join('\n')+'\n');
for(const f of doc.families)console.log(f.family,'n',f.folds.length,'train',f.nTrain,'MAPE(theta, ridge)',f.scores.theta.mape.toFixed(3),f.scores.ridge.mape.toFixed(3),'descriptor OOD n',f.support.outsideDescriptor);
console.log('macro MAPE',doc.overall.macro.theta.mape,doc.overall.macro.ridge.mape);
