'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const web=[process.argv[2],path.join(root,'dist'),root].find(d=>d&&fs.existsSync(path.join(d,'family-intrinsic-data.js')));
const dir=path.join(path.resolve(web),'family-inputs');
const input=process.argv[3]||path.join(dir,'external-theta-ps.json');
const manifest=process.argv[4]||path.join(dir,'theta-ps-frozen.json');
const script=[path.join(root,'scripts/build-external-theta.cjs'),path.join(__dirname,'build-external-theta.cjs')].find(f=>fs.existsSync(f));
const {run,normalize,inspect,checkFreeze}=require(script);
const baseFile=path.join(path.resolve(web),'family-intrinsic-data.js');
const old=require(baseFile).rows, dto=JSON.parse(fs.readFileSync(input));
const frozen=checkFreeze(manifest,baseFile,old),x=require(path.join(path.resolve(web),'family-engine.js')).descriptor('PS').logBondsPerMass;
const b=run(dto,old,frozen,x);
const byStudy=k=>b.studies.find(s=>s.study===k);
assert.equal(byStudy('miyaki1980').status,'strict');
assert.equal(byStudy('miyaki1980').n,2);
assert.equal(byStudy('miyaki1980').outsideTrainingMass,2); 
assert.ok(Math.abs(byStudy('miyaki1980').scores.control.mape-7.858818994848543)<1e-8);
assert.equal(byStudy('azim1985').status,'sensitivity'); assert.equal(byStudy('berry1967').status,'sensitivity');
assert.equal(byStudy('azim1985').n,5);assert.equal(byStudy('berry1967').n,16);
assert.deepEqual(byStudy('azim1985').flags,['mass_basis']);assert.deepEqual(byStudy('berry1967').flags,['temperature']);
assert.ok(Math.abs(byStudy('berry1967').scores.control.mape-2.7521136965356154)<1e-8);
const table=normalize(b,dto.sources);
assert.ok(table.some(p=>p.id==='theta-external-azim1985-sensitivity'));
assert.throws(()=>run({...dto,rows:[dto.rows[0],dto.rows[0]]},old,frozen,x));
const first=dto.rows.find(r=>r.study==='azim1985'),s=dto.sources[first.study];
const m={...s,mass_basis:'Mw'},r={...first,mass_basis:'Mw'};
assert.deepEqual(inspect(r,m,old),['unverified_independent_origin']);
assert.deepEqual(inspect(r,{...m,strictEligible:true,independence_note:'method branch test',primary_location:'table test'},old),[]);
const bad={...s,knownOverlap:true};
assert.ok(inspect(first,bad,old).includes('documented_sample_reuse'));
assert.ok(inspect({...first,T_C:23},s,old).includes('invalid_provenance'));
const alt=run({...dto,rows:dto.rows.map(r=>({...r,eta_mL_g:r.eta_mL_g*17}))},old,frozen,x);
for(let k=0;k<b.rows.length;k++){
  assert.equal(alt.rows[k].baseline,b.rows[k].baseline);
  assert.equal(alt.rows[k].adaptive,b.rows[k].adaptive);
  assert.equal(alt.rows[k].control,b.rows[k].control);
  assert.equal(alt.rows[k].status,b.rows[k].status);
}
console.log('PASS external PS, frozen-data checks, condition mismatch, strict eligibility, duplicate and overlap checks and target-label invariance.');
